/** Legt Schema und Protokolltabelle an und führt fehlende Migrationen aus (mehrfach aufrufbar, parallel sicher). */
export async function migrate(db: Sql, migrations: Migration[] = MIGRATIONS): Promise<string[]> {
  const schema = await db.one(`SELECT 1 AS ok FROM pg_namespace WHERE nspname = 'keleo'`);
  if (!schema) await db.exec('CREATE SCHEMA keleo');
  await db.exec(`CREATE TABLE IF NOT EXISTS keleo.schema_migrations (name text PRIMARY KEY, applied_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'))`);
  return db.tx(async (t) => {
    await t.exec(`SELECT pg_advisory_xact_lock(${LOCK_ID})`);
    const applied = new Set((await t.query<{ name: string }>('SELECT name FROM keleo.schema_migrations')).map((r) => r.name));
    const done: string[] = [];
    for (const m of migrations) {
      if (applied.has(m.name)) continue;
      await t.exec(m.sql);
      await t.exec('INSERT INTO keleo.schema_migrations (name) VALUES ($1)', [m.name]);
      done.push(m.name);
    }
    return done;
  });
}
